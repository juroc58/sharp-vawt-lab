"""
Test that all result JSONs have valid freshness stamps (schema v2).

Ensures every result JSON was generated by the current version of its
generating script and that every relevant source/data dependency is covered
by the stamp.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "scripts"))

from scripts.stamp import (
    SCRIPT_VERSIONS,
    STAMP_CHECK_MAP,
    STAMP_SCHEMA_VERSION,
    list_stale_results,
)

HEX64 = re.compile(r"^[0-9a-f]{64}$")


def test_all_result_jsons_have_valid_stamps():
    """Test that all result JSONs have valid, current stamps."""
    stale = list_stale_results()

    if stale:
        for fpath, msg in stale:
            print(f"STALE: {fpath} - {msg}")
        stale_files = [fpath for fpath, _ in stale]
        raise AssertionError(
            f"Found {len(stale)} stale result JSON(s): {', '.join(stale_files)}. "
            f"Re-run the generating scripts to update."
        )


def test_stamp_map_has_unique_keys():
    """STAMP_CHECK_MAP keys must be unique by construction."""
    keys = list(STAMP_CHECK_MAP.keys())
    assert len(keys) == len(set(keys)), f"duplicate keys in STAMP_CHECK_MAP: {keys}"


def test_every_result_json_mapped_once():
    """Every generated result JSON appears exactly once in the stamp map."""
    scripts_dir = os.path.join(os.path.dirname(__file__), "..", "scripts")
    mapped = set(STAMP_CHECK_MAP.keys())
    on_disk = {p.name for p in __import__("pathlib").Path(scripts_dir).glob("*.json")}
    on_disk.discard("optimization_overrides.json")  # input override, not a result
    assert on_disk == mapped, (
        f"unmapped: {sorted(on_disk - mapped)}; missing from disk: {sorted(mapped - on_disk)}"
    )


def test_every_script_has_semantic_version():
    """Every mapped script has a non-generic semantic version."""
    for script in STAMP_CHECK_MAP.values():
        version = SCRIPT_VERSIONS.get(script)
        assert version, f"no semantic version for {script}"
        assert version not in ("", "v1.0", "1.0", "1.0.0", "v1"), f"generic version for {script}: {version}"
        parts = version.split(".")
        assert len(parts) == 3 and all(p.isdigit() for p in parts), version


def test_stamp_structure():
    """Test that stamp fields match schema v2."""
    scripts_dir = os.path.join(os.path.dirname(__file__), "..", "scripts")

    for json_name, script_path in STAMP_CHECK_MAP.items():
        json_path = os.path.join(scripts_dir, json_name)

        if not os.path.exists(json_path):
            continue

        with open(json_path) as f:
            data = json.load(f)

        assert "stamp" in data, f"{json_name}: missing 'stamp' field"
        stamp = data["stamp"]

        assert stamp.get("schema_version") == STAMP_SCHEMA_VERSION, (
            f"{json_name}: stamp schema {stamp.get('schema_version')} != {STAMP_SCHEMA_VERSION}"
        )
        assert stamp.get("script") == script_path, (
            f"{json_name}: stamp script {stamp.get('script')} != {script_path}"
        )

        required_fields = [
            "code_hash", "script", "script_version", "created_utc",
            "python_version", "git_commit", "script_args", "source_hashes",
            "data_hashes", "config_hash",
        ]
        for field in required_fields:
            assert field in stamp, f"{json_name}: stamp missing field '{field}'"

        assert HEX64.match(stamp["code_hash"]), (
            f"{json_name}: code_hash should be 64-char hex, got {stamp.get('code_hash')!r}"
        )
        assert stamp["source_hashes"], f"{json_name}: source_hashes empty"
        assert stamp["data_hashes"], f"{json_name}: data_hashes empty"
        assert stamp["config_hash"], f"{json_name}: config_hash empty"

        # The stamp's script_version must be registered and non-generic.
        assert stamp["script_version"] == SCRIPT_VERSIONS[script_path], (
            f"{json_name}: stamp version {stamp['script_version']} != registered {SCRIPT_VERSIONS[script_path]}"
        )


def test_stamp_covers_core_sources():
    """Every stamp must cover the source modules that can affect results."""
    scripts_dir = os.path.join(os.path.dirname(__file__), "..", "scripts")
    core = {
        "sharp_vawt/__init__.py", "sharp_vawt/config.py",
        "sharp_vawt/database.py", "sharp_vawt/engine.py",
        "vawt_core.py", "vawt_presets.py",
    }

    for json_name, script_path in STAMP_CHECK_MAP.items():
        json_path = os.path.join(scripts_dir, json_name)
        if not os.path.exists(json_path):
            continue
        with open(json_path) as f:
            stamp = json.load(f)["stamp"]
        provided = set(stamp["source_hashes"])
        assert core <= provided, (
            f"{json_name}: stamp omits core sources {sorted(core - provided)}"
        )
        assert script_path in provided, (
            f"{json_name}: stamp omits its own script {script_path}"
        )


