#!/usr/bin/env python3
"""
Test that all result JSONs have valid freshness stamps.

This test ensures that result JSONs were generated by the current version
of their generating scripts and that the underlying code/data hasn't changed
since they were generated.
"""
import sys
import os
import json

# Add scripts directory to path
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "scripts"))

from stamp import list_stale_results, verify_stamp


def test_all_result_jsons_have_valid_stamps():
    """Test that all result JSONs have valid, current stamps."""
    stale = list_stale_results()
    
    if stale:
        # Print details for debugging
        for fpath, msg in stale:
            print(f"STALE: {fpath} - {msg}")
        
        # Fail the test with a clear message
        stale_files = [fpath for fpath, _ in stale]
        raise AssertionError(
            f"Found {len(stale)} stale result JSON(s): {', '.join(stale_files)}. "
            f"Re-run the generating scripts to update."
        )


def test_stamp_structure():
    """Test that stamp fields have the expected structure."""
    from stamp import STAMP_CHECK_MAP
    
    scripts_dir = os.path.join(os.path.dirname(__file__), "..", "scripts")
    
    for json_name, script_path in STAMP_CHECK_MAP.items():
        json_path = os.path.join(os.path.dirname(__file__), "..", "scripts", json_name)
        
        if not os.path.exists(json_path):
            continue  # Skip files that don't exist yet
        
        with open(json_path) as f:
            data = json.load(f)
        
        # Check stamp structure
        assert "stamp" in data, f"{json_name}: missing 'stamp' field"
        stamp = data["stamp"]
        
        required_fields = ["code_hash", "script", "script_version", "created_utc"]
        for field in required_fields:
            assert field in stamp, f"{json_name}: stamp missing field '{field}'"
        
        assert stamp["script"] == STAMP_CHECK_MAP.get(json_name, ""), \
            f"{json_name}: stamp script mismatch"
        
        # Verify hash is 16-char hex
        assert len(stamp["code_hash"]) == 16, \
            f"{json_name}: code_hash should be 16-char hex"
        assert all(c in "0123456789abcdef" for c in stamp["code_hash"]), \
            f"{json_name}: code_hash should be hex"


if __name__ == "__main__":
    # Run tests manually if not using pytest
    try:
        test_all_result_jsons_have_valid_stamps()
        print("All result JSONs have valid stamps")
    except AssertionError as e:
        print(f"FAIL: {e}")
        sys.exit(1)
    
    try:
        test_stamp_structure()
        print("All stamps have valid structure")
    except AssertionError as e:
        print(f"FAIL: {e}")
        sys.exit(1)
    
    print("All freshness tests passed!")